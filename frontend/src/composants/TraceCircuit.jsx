/**
 * Tracés de circuits — `assets/gp-cards.svg` découpé en composant.
 *
 * **Ce que la planche contient vraiment, et l'écart que cela impose.** Le
 * fichier dessine six cartes de Grand Prix, mais seulement **deux tracés
 * distincts** : Monza et Spa, répétés trois fois chacun sous des aplats de
 * couleur différents. Les libellés le confirment — « Monza », « Spa », et la
 * même date « 27 août 2026 » sur les six. C'est une planche de maquette, pas un
 * jeu de vingt-quatre circuits.
 *
 * Les deux vrais tracés sont donc extraits **tels quels**, sans être redessinés,
 * et rattachés aux Grands Prix qu'ils représentent (Monza = GP Italie, Spa = GP
 * Belgique). Tous les autres reçoivent un **tracé générique**. C'est ce que la
 * demande prévoyait explicitement, et c'est aussi la seule option honnête :
 * inventer vingt-deux circuits à main levée donnerait des formes qui ne
 * ressemblent à rien, ce qui est pire qu'un motif assumé comme neutre.
 *
 * Les `viewBox` ne sont pas arrondies au hasard : ce sont les boîtes englobantes
 * réelles des deux tracés, mesurées en échantillonnant leurs courbes de Bézier.
 * Les données de chemin restent donc **identiques au fichier d'origine**, aucune
 * coordonnée n'est réécrite — c'est le cadrage qui bouge, pas le dessin.
 *
 * Le tracé prend `currentColor` : posé sur un aplat, il en épouse le texte.
 */

/** Rapprochement nom de Grand Prix → tracé. Le nom vient d'Unibet, dont
 *  l'orthographe bouge (« GP Pays Bas » puis « GP Pays-Bas ») : la
 *  reconnaissance se fait sur un nom normalisé, jamais sur l'égalité stricte. */
const PAR_MOTIF = [
  [/itali|monza/, "monza"],
  [/belgi|spa|francorchamps/, "spa"],
];

function normaliser(nom) {
  return String(nom ?? "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
}

/** Le tracé d'un Grand Prix, ou `"generique"` si la planche n'en a pas. */
export function traceDuGrandPrix(nom) {
  const cle = normaliser(nom);
  for (const [motif, trace] of PAR_MOTIF) {
    if (motif.test(cle)) return trace;
  }
  return "generique";
}

